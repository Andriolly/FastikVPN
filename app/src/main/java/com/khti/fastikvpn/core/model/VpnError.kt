package com.khti.fastikvpn.core.model

// Причины, по которым VPN не включился или не заработал.
// Это перечисление (enum): список заранее известных вариантов.
// Преимущество перед обычной строкой: компилятор следит, чтобы мы обработали все варианты,
// а в коде нельзя опечататься в названии ошибки.
// Лежит в core/model, потому что ошибку создаёт сервис, а показывает экран.
enum class VpnError {
    // Ссылка на сервер не задана или не разобралась
    INVALID_SERVER_LINK,

    // Система не создала виртуальную сетевую карту
    TUNNEL_NOT_CREATED,

    // Ядро Xray не запустилось
    CORE_START_FAILED,

    // VPN включён, но сервер не отвечает на проверочный запрос
    SERVER_UNREACHABLE,

    // Любая непредвиденная ошибка
    UNKNOWN
}