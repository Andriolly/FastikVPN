package com.khti.fastikvpn.core.model

/**
 * Режим темы приложения. Это то, что пользователь выбирает в настройках.
 *
 * SYSTEM - следовать теме телефона (по умолчанию);
 * DARK   - всегда тёмная;
 * LIGHT  - всегда светлая.
 *
 * Лежит в core/model, потому что нужен сразу нескольким слоям:
 * теме (UI), репозиторию настроек (data) и экрану настроек.
 */
enum class ThemeMode {
    SYSTEM,
    DARK,
    LIGHT
}