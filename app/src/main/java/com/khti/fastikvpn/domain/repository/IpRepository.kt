package com.khti.fastikvpn.domain.repository

// Экран и ViewModel знают только про этот интерфейс и не знают, откуда адрес берётся.
// Потом источником может стать наш сервер, а остальной код менять не придётся.
interface IpRepository {

    // suspend значит, что функция может ждать (запрос в сеть идёт не мгновенно),
    // не замораживая экран. Вернёт null, если определить адрес не удалось.
    suspend fun getPublicIp(): String?
}